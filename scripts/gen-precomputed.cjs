/* Regenerates precomputed.js: the finished search of every clueless board.
   The empty board is the one puzzle the solver is asked for over and over —
   it is what the Create tab opens on — and it is also the most expensive one
   (an 8x8 has 4,638,576 single-loop solutions). Nothing about it varies, so
   the counts are baked in here instead of being re-derived in the browser.
   Run with `node scripts/gen-precomputed.cjs` from the repo root; takes ~15 s.
   Boards with an odd number of dots are skipped: the engine rejects those on
   sight, so there is nothing to wait for. */
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { Fences } = require('../fences-engine.js');

const MAX = 8;   // largest board side, in dots
const LOOPS = 1; // single-loop puzzles only; multi-loop searches are far larger

const pack = counts => Array.from(counts, n => n.toString(36)).join('.');

const rows = [];
for (let R = 2; R <= MAX; R++) {
  for (let C = 2; C <= MAX; C++) {
    if ((R * C) % 2) continue; // odd dot count: no 2-factor exists, engine says so instantly
    const t0 = Date.now();
    const eng = new Fences(R, C, new Set(), { loops: LOOPS });
    while (!eng.done) eng.run(250);
    const ms = Date.now() - t0;
    console.log(`${R}x${C}: ${eng.solutions.toLocaleString('en-US')} solutions, ${ms} ms`);
    rows.push(`  '${R}x${C}': [${eng.solutions}, ${eng.nodes}, ` +
      `'${pack(eng.heat)}', '${pack(eng.cellHeat)}'],`);
  }
}

const out = `/* Finished searches of the clueless board, one loop, up to ${MAX}x${MAX} dots.
   Generated by scripts/gen-precomputed.cjs — regenerate rather than hand-edit.
   Each entry is [solutions, states explored, edge tallies, cell tallies]; the
   two tallies are base-36 counts in engine index order, joined by dots: how
   many solutions use each edge, and how many enclose each cell. */
globalThis.FencesPrecomputed = {
${rows.join('\n')}
};
if (typeof module !== 'undefined') module.exports = globalThis.FencesPrecomputed;
`;

writeFileSync(join(__dirname, '..', 'precomputed.js'), out);
console.log(`Wrote precomputed.js (${rows.length} boards).`);
